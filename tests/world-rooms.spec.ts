import { test, expect } from '@playwright/test';

test('world rooms show activities, corrected retina, fantasy shelves and city maps', async ({ page }) => {
  await page.goto('/');
  const dialog = page.getByRole('dialog').first();
  const close = async () => page.getByRole('button', { name: 'Close details' }).click();
  await page.getByRole('button', { name: 'Explore Art studio', exact: true }).click();
  await expect(dialog.getByRole('application', { name: 'Drawing canvas' })).toBeVisible();
  await expect(dialog.locator('img')).toHaveCount(0);
  await close();
  await page.getByRole('button', { name: 'Explore Vision lab', exact: true }).click();
  await dialog.getByRole('button', { name: 'Macular region', exact: true }).click();
  await expect(dialog.getByRole('img')).toHaveAccessibleName(/Macula crop centered on the fovea/);
  await expect(dialog.getByRole('status')).toContainText('temporal to the optic disc');
  await page.screenshot({ path: 'retina-check.png' });
  await close();
  await page.getByRole('button', { name: 'Explore Library / CV', exact: true }).click();
  await dialog.getByRole('button', { name: '+ Wand', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('Wand');
  await dialog.getByRole('button', { name: 'The Lord of the Rings', exact: true }).click();
  await dialog.getByRole('button', { name: '+ Lembas bread', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('Lembas bread');
  await close();
  await page.getByRole('button', { name: 'Explore Home / About Eric', exact: true }).click();
  await expect(dialog.locator('iframe')).toHaveAttribute('src', /San%20Francisco/);
  await expect(dialog.getByRole('link', { name: 'Explore San Francisco in Google Maps' })).toHaveAttribute('href', /api=1/);
  await close();
  await page.getByRole('button', { name: 'Explore Travel / Conferences', exact: true }).click();
  await dialog.getByRole('button', { name: 'Tokyo', exact: true }).click();
  await expect(dialog.locator('iframe')).toHaveAttribute('title', 'Map of Tokyo');
  await expect(dialog.getByRole('link', { name: 'Explore Tokyo in Google Maps' })).toBeVisible();
  await expect(dialog).not.toContainText('detour');
  await close();
  await page.getByRole('button', { name: 'Explore Music room', exact: true }).click();
  await dialog.getByRole('button', { name: 'Ride U', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('Ride');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'drums-mobile-check.png' });
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
});
